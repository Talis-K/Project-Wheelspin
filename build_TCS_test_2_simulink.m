function code = tyreCode(P)
lines = { ...
    'function [Fx,Fz,ax] = tyreVehicle(kappa,Vx,muRoad)'; ...
    '%#codegen'; ...
    sprintf('m = %.17g;',P.vehicleMass); ...
    sprintf('g = %.17g;',P.g); ...
    sprintf('rearFraction = %.17g;',P.rearStaticFraction); ...
    sprintf('h = %.17g;',P.cgHeight); ...
    sprintf('L = %.17g;',P.wheelbase); ...
    sprintf('Crr = %.17g;',P.rollingResistance); ...
    sprintf('rho = %.17g;',P.airDensity); ...
    sprintf('CdA = %.17g;',P.dragArea); ...
    sprintf('B = %.17g;',P.magicB); ...
    sprintf('C = %.17g;',P.magicC); ...
    sprintf('E = %.17g;',P.magicE); ...
    'k = min(max(kappa,-5.0),5.0);'; ...
    'argument = B*k-E*(B*k-atan(B*k));'; ...
    'shape = sin(C*atan(argument));'; ...
    'q = max(muRoad,0.0)*shape;'; ...
    'rollingForce = Crr*m*g*tanh(Vx/0.20);'; ...
    'dragForce = 0.5*rho*CdA*Vx*abs(Vx);'; ...
    'resistancePerMass = (rollingForce+dragForce)/m;'; ...
    'denominator = max(1.0-q*h/L,0.25);'; ...
    'ax = (q*g*rearFraction-resistancePerMass)/denominator;'; ...
    'Fz = max((m*g*rearFraction+m*ax*h/L)/2.0,0.0);'; ...
    'Fx = q*Fz;'; ...
    'end'};
code = strjoin(lines,sprintf('\n'));
end

