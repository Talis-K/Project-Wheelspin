%% LOCAL BUILDER FUNCTIONS
function buildController(sys,P)
clearSystem(sys);

inputNames = {'Driver torque','Motor resolver rpm','Reference wheel rpm', ...
    'Estimated road mu','TCS enable'};
inputY = [45 100 155 210 265];
for k = 1:numel(inputNames)
    addInport(sys,inputNames{k},k,[20 inputY(k) 50 inputY(k)+20]);
    add_block('simulink/Discrete/Zero-Order Hold', ...
        [sys '/Sample ' inputNames{k}], ...
        'SampleTime',num2str(P.controllerSampleTime,'%.15g'), ...
        'Position',[90 inputY(k)-5 170 inputY(k)+25]);
end

core = [sys '/Embedded TCS Algorithm'];
add_block('simulink/User-Defined Functions/MATLAB Function',core, ...
    'Position',[245 55 520 300]);
setMATLABFunctionCode(core,controllerCode(P),P.controllerSampleTime);

outputNames = {'Torque command','Filtered slip','Admissible torque', ...
    'Motor torque limit','Controller state','Active flag', ...
    'Measured vehicle speed','Measured tread speed'};
outputY = [40 85 130 175 220 265 310 355];
for k = 1:numel(outputNames)
    addOutport(sys,outputNames{k},k,[610 outputY(k) 640 outputY(k)+20]);
end

for k = 1:numel(inputNames)
    wire(sys,[inputNames{k} '/1'],['Sample ' inputNames{k} '/1'],'');
    wire(sys,['Sample ' inputNames{k} '/1'], ...
        sprintf('Embedded TCS Algorithm/%d',k),'');
end
for k = 1:numel(outputNames)
    wire(sys,sprintf('Embedded TCS Algorithm/%d',k), ...
        [outputNames{k} '/1'],outputNames{k});
end

addAnnotation(sys,[205 5 565 35],sprintf( ...
    'Microcontroller task: Ts = %.1f ms',1000*P.controllerSampleTime));
end

function code = controllerCode(P)
lines = { ...
    'function [Tcmd,kappaFiltered,Tadmissible,TmotorLimit,state,active,Vx,Vtread] = tcsController(Tdriver,motorRPM,referenceRPM,muEstimate,tcsEnable)'; ...
    '%#codegen'; ...
    '% Sampled single-wheel traction controller.'; ...
    'persistent kFilter z previousCommand stateMemory activationTimer releaseTimer recoveryTimer previousVx accelerationFilter'; ...
    'if isempty(kFilter)'; ...
    '    kFilter = 0.0; z = 0.0; previousCommand = 0.0;'; ...
    '    stateMemory = 0.0; activationTimer = 0.0; releaseTimer = 0.0;'; ...
    '    recoveryTimer = 0.0; previousVx = 0.0; accelerationFilter = 0.0;'; ...
    'end'; ...
    sprintf('Ts = %.17g;',P.controllerSampleTime); ...
    sprintf('r = %.17g;',P.tyreRadius); ...
    sprintf('G = %.17g;',P.gearRatio); ...
    sprintf('eta = %.17g;',P.drivetrainEfficiency); ...
    sprintf('diffSplit = %.17g;',P.differentialSplit); ...
    sprintf('mass = %.17g;',P.vehicleMass); ...
    sprintf('g = %.17g;',P.g); ...
    sprintf('rearFraction = %.17g;',P.rearStaticFraction); ...
    sprintf('h = %.17g;',P.cgHeight); ...
    sprintf('L = %.17g;',P.wheelbase); ...
    sprintf('Tpeak = %.17g;',P.motorPeakTorque); ...
    sprintf('Ppeak = %.17g;',P.motorPeakPower); ...
    sprintf('rpmMaximum = %.17g;',P.motorMaximumRPM); ...
    sprintf('rpmResolution = %.17g;',P.sensorResolutionRPM); ...
    sprintf('vGuard = %.17g;',P.slipDenominatorGuard); ...
    sprintf('tauFilter = %.17g;',P.slipFilterTimeConstant); ...
    sprintf('kappaTarget = %.17g;',P.slipTarget); ...
    sprintf('kappaOn = %.17g;',P.slipActivation); ...
    sprintf('kappaOff = %.17g;',P.slipRelease); ...
    sprintf('enableSpeed = %.17g;',P.controlEnableSpeed); ...
    sprintf('activationTime = %.17g;',P.activationPersistence); ...
    sprintf('releaseTime = %.17g;',P.releasePersistence); ...
    sprintf('recoveryTimeLimit = %.17g;',P.recoveryTime); ...
    sprintf('launchSlipVelocity = %.17g;',P.launchSlipVelocity); ...
    sprintf('launchVelocityGain = %.17g;',P.launchVelocityGain); ...
    sprintf('launchTorque = %.17g;',P.launchTorqueCap); ...
    sprintf('safetyFactor = %.17g;',P.admissibleTorqueSafetyFactor); ...
    sprintf('Kp = %.17g;',P.Kp); ...
    sprintf('Ki = %.17g;',P.Ki); ...
    sprintf('Kaw = %.17g;',P.Kaw); ...
    sprintf('zMinimum = %.17g;',P.integratorMinimum); ...
    sprintf('zMaximum = %.17g;',P.integratorMaximum); ...
    sprintf('cutRate = %.17g;',P.torqueCutRate); ...
    sprintf('restoreRate = %.17g;',P.torqueRestoreRate); ...
    sprintf('faultTorque = %.17g;',P.faultTorque); ...
    ''; ...
    '% Quantised sensor measurements.'; ...
    'motorRPMq = rpmResolution*round(motorRPM/rpmResolution);'; ...
    'referenceRPMq = rpmResolution*round(referenceRPM/rpmResolution);'; ...
    'sensorValid = isfinite(motorRPMq) && isfinite(referenceRPMq) && motorRPMq >= 0.0 && referenceRPMq >= 0.0;'; ...
    'if sensorValid'; ...
    '    omegaWheel = motorRPMq*(2.0*pi/60.0)/G;'; ...
    '    Vtread = r*omegaWheel;'; ...
    '    Vx = referenceRPMq*(2.0*pi/60.0)*r;'; ...
    '    slipVelocity = Vtread-Vx;'; ...
    '    kappaRaw = slipVelocity/max(abs(Vx),vGuard);'; ...
    '    kappaRaw = min(max(kappaRaw,-3.0),3.0);'; ...
    'else'; ...
    '    Vx = previousVx; Vtread = Vx; slipVelocity = 0.0; kappaRaw = 0.0;'; ...
    'end'; ...
    'alpha = Ts/(tauFilter+Ts);'; ...
    'kFilter = kFilter+alpha*(kappaRaw-kFilter);'; ...
    'kappaFiltered = kFilter;'; ...
    ''; ...
    '% Physical motor torque-speed envelope.'; ...
    'omegaMotor = max(abs(motorRPMq)*2.0*pi/60.0,1.0);'; ...
    'if ~sensorValid || motorRPMq >= rpmMaximum'; ...
    '    TmotorLimit = 0.0;'; ...
    'else'; ...
    '    TmotorLimit = min(Tpeak,Ppeak/omegaMotor);'; ...
    'end'; ...
    ''; ...
    '% Longitudinal load estimate for precautionary torque.'; ...
    'rawAcceleration = min(max((Vx-previousVx)/Ts,-15.0),15.0);'; ...
    'accelerationFilter = accelerationFilter+0.15*(rawAcceleration-accelerationFilter);'; ...
    'previousVx = Vx;'; ...
    'rearLoad = mass*g*rearFraction+mass*accelerationFilter*h/L;'; ...
    'FzEstimate = max(rearLoad/2.0,0.0);'; ...
    'Tadmissible = safetyFactor*max(muEstimate,0.0)*FzEstimate*r/(G*eta*diffSplit);'; ...
    'Tadmissible = min(max(Tadmissible,0.0),TmotorLimit);'; ...
    ''; ...
    'requested = min(max(Tdriver,0.0),TmotorLimit);'; ...
    'lowSpeed = Vx < enableSpeed;'; ...
    'if lowSpeed'; ...
    '    launchFeedback = max(launchTorque-launchVelocityGain*max(slipVelocity-launchSlipVelocity,0.0),0.0);'; ...
    '    proactiveCap = min(requested,min(Tadmissible,launchFeedback));'; ...
    'else'; ...
    '    proactiveCap = min(requested,Tadmissible);'; ...
    'end'; ...
    ''; ...
    '% State supervisor: 0 OFF, 1 LAUNCH, 2 ARMED, 3 ACTIVE, 4 RECOVERY, 5 FAULT.'; ...
    'if ~sensorValid'; ...
    '    stateMemory = 5.0;'; ...
    'elseif tcsEnable == 0 || requested < 0.01'; ...
    '    stateMemory = 0.0;'; ...
    '    activationTimer = 0.0; releaseTimer = 0.0; recoveryTimer = 0.0;'; ...
    'elseif lowSpeed'; ...
    '    stateMemory = 1.0;'; ...
    '    activationTimer = 0.0; releaseTimer = 0.0; recoveryTimer = 0.0;'; ...
    'else'; ...
    '    if stateMemory == 0.0 || stateMemory == 1.0 || stateMemory == 5.0'; ...
    '        stateMemory = 2.0;'; ...
    '    end'; ...
    '    if kFilter > kappaOn'; ...
    '        activationTimer = activationTimer+Ts;'; ...
    '    else'; ...
    '        activationTimer = 0.0;'; ...
    '    end'; ...
    '    if kFilter < kappaOff'; ...
    '        releaseTimer = releaseTimer+Ts;'; ...
    '    else'; ...
    '        releaseTimer = 0.0;'; ...
    '    end'; ...
    '    if stateMemory == 2.0 && activationTimer >= activationTime'; ...
    '        stateMemory = 3.0; releaseTimer = 0.0;'; ...
    '    elseif stateMemory == 3.0 && releaseTimer >= releaseTime'; ...
    '        stateMemory = 4.0; recoveryTimer = 0.0;'; ...
    '    elseif stateMemory == 4.0'; ...
    '        if kFilter > kappaOn'; ...
    '            stateMemory = 3.0; releaseTimer = 0.0;'; ...
    '        else'; ...
    '            recoveryTimer = recoveryTimer+Ts;'; ...
    '            if recoveryTimer >= recoveryTimeLimit'; ...
    '                stateMemory = 2.0; recoveryTimer = 0.0;'; ...
    '            end'; ...
    '        end'; ...
    '    end'; ...
    'end'; ...
    ''; ...
    'if stateMemory == 3.0'; ...
    '    active = 1.0;'; ...
    'else'; ...
    '    active = 0.0;'; ...
    'end'; ...
    'if active ~= 0.0'; ...
    '    slipError = kappaTarget-kFilter;'; ...
    '    unsaturatedCap = proactiveCap+Kp*slipError+Ki*z;'; ...
    '    reactiveCap = min(max(unsaturatedCap,0.0),proactiveCap);'; ...
    '    zDerivative = slipError+Kaw*(reactiveCap-unsaturatedCap);'; ...
    '    z = min(max(z+Ts*zDerivative,zMinimum),zMaximum);'; ...
    'else'; ...
    '    reactiveCap = proactiveCap;'; ...
    '    if stateMemory ~= 4.0'; ...
    '        z = 0.0;'; ...
    '    end'; ...
    'end'; ...
    ''; ...
    'if stateMemory == 5.0'; ...
    '    desiredTorque = faultTorque;'; ...
    'elseif tcsEnable ~= 0'; ...
    '    desiredTorque = reactiveCap;'; ...
    'else'; ...
    '    desiredTorque = requested;'; ...
    'end'; ...
    'if stateMemory == 5.0'; ...
    '    Tcmd = faultTorque;'; ...
    'else'; ...
    '    torqueChange = desiredTorque-previousCommand;'; ...
    '    torqueChange = min(max(torqueChange,-cutRate*Ts),restoreRate*Ts);'; ...
    '    Tcmd = min(max(previousCommand+torqueChange,0.0),TmotorLimit);'; ...
    'end'; ...
    'previousCommand = Tcmd;'; ...
    'state = stateMemory;'; ...
    'end'};
code = strjoin(lines,sprintf('\n'));
end

function buildPlant(sys,P)
clearSystem(sys);
addInport(sys,'Motor torque command',1,[20 55 50 75]);
addInport(sys,'Actual road mu',2,[20 300 50 320]);

add_block('simulink/Continuous/Transfer Fcn',[sys '/Motor response'], ...
    'Numerator','1','Denominator',sprintf('[%.17g 1]',P.motorTimeConstant), ...
    'Position',[90 40 190 90]);
drivelineGain = P.gearRatio*P.drivetrainEfficiency*P.differentialSplit;
add_block('simulink/Math Operations/Gain',[sys '/Wheel-side torque'], ...
    'Gain',num2str(drivelineGain,'%.17g'),'Position',[230 40 335 90]);

add_block('simulink/Continuous/Integrator',[sys '/Wheel speed state'], ...
    'InitialCondition','0','LimitOutput','on','LowerSaturationLimit','0', ...
    'UpperSaturationLimit','inf','Position',[805 45 845 95]);
add_block('simulink/Continuous/Integrator',[sys '/Vehicle speed state'], ...
    'InitialCondition','0','LimitOutput','on','LowerSaturationLimit','0', ...
    'UpperSaturationLimit','inf','Position',[805 375 845 425]);

add_block('simulink/Math Operations/Gain',[sys '/True tread speed'], ...
    'Gain',num2str(P.tyreRadius,'%.17g'),'Position',[100 140 190 185]);
add_block('simulink/Math Operations/Sum',[sys '/True slip velocity'], ...
    'Inputs','+-','Position',[235 185 270 230]);
add_block('simulink/Math Operations/Abs',[sys '/Absolute vehicle speed'], ...
    'Position',[105 245 145 280]);
add_block('simulink/Sources/Constant',[sys '/Slip denominator guard'], ...
    'Value',num2str(P.slipDenominatorGuard,'%.17g'), ...
    'Position',[190 315 250 345]);
add_block('simulink/Math Operations/MinMax',[sys '/Guarded denominator'], ...
    'Function','max','Inputs','2','Position',[290 260 345 320]);
add_block('simulink/Math Operations/Product',[sys '/True slip ratio'], ...
    'Inputs','*/','Position',[395 205 445 255]);

tyreBlock = [sys '/Nonlinear tyre and load transfer'];
add_block('simulink/User-Defined Functions/MATLAB Function',tyreBlock, ...
    'Position',[500 175 665 350]);
setMATLABFunctionCode(tyreBlock,tyreCode(P));

add_block('simulink/Math Operations/Gain',[sys '/Tyre reaction torque'], ...
    'Gain',num2str(P.tyreRadius,'%.17g'),'Position',[690 135 775 175]);
add_block('simulink/Math Operations/Sum',[sys '/Net wheel torque'], ...
    'Inputs','+-','Position',[410 45 445 90]);
add_block('simulink/Math Operations/Gain',[sys '/Wheel angular acceleration'], ...
    'Gain',num2str(1/P.wheelEquivalentInertia,'%.17g'), ...
    'Position',[685 45 775 95]);

outputNames = {'Wheel angular speed','Vehicle speed','True slip', ...
    'Tyre force','Normal load','Acceleration'};
outputY = [40 100 160 220 280 340];
for k = 1:numel(outputNames)
    addOutport(sys,outputNames{k},k,[920 outputY(k) 950 outputY(k)+20]);
end

wire(sys,'Motor torque command/1','Motor response/1','T_command');
wire(sys,'Motor response/1','Wheel-side torque/1','T_motor');
wire(sys,'Wheel-side torque/1','Net wheel torque/1','T_wheel');
wire(sys,'Wheel speed state/1','True tread speed/1','omega_wheel');
wire(sys,'True tread speed/1','True slip velocity/1','V_tread');
wire(sys,'Vehicle speed state/1','True slip velocity/2','Vx');
wire(sys,'Vehicle speed state/1','Absolute vehicle speed/1','');
wire(sys,'Absolute vehicle speed/1','Guarded denominator/1','');
wire(sys,'Slip denominator guard/1','Guarded denominator/2','');
