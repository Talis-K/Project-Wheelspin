function configureSlider(block,minimumTorque,maximumTorque,initialTorque)
% Set limits before gain because Simulink validates gain immediately.
parameters = get_param(block,'DialogParameters');
if isfield(parameters,'low')
    set_param(block,'low',num2str(minimumTorque,'%.15g'));
end
if isfield(parameters,'high')
    set_param(block,'high',num2str(maximumTorque,'%.15g'));
end
if isfield(parameters,'Minimum')
    set_param(block,'Minimum',num2str(minimumTorque,'%.15g'));
end
if isfield(parameters,'Maximum')
    set_param(block,'Maximum',num2str(maximumTorque,'%.15g'));
end
% Gain is deliberately assigned only after the valid range exists.
if isfield(parameters,'gain')
    set_param(block,'gain',num2str(initialTorque,'%.15g'));
elseif isfield(parameters,'Gain')
    set_param(block,'Gain',num2str(initialTorque,'%.15g'));
else
    error('TCSBuilder:SliderGainParameter', ...
        'Could not identify the Slider Gain value parameter.');
end
end

function addCompatibleStep(path,stepTime,initialValue,finalValue,position)
% Support both legacy and R2026a Step-block parameter names.
add_block('simulink/Sources/Step',path,'Position',position);
set_param(path,'Time',num2str(stepTime,'%.15g'),'SampleTime','0');
parameters = get_param(path,'DialogParameters');
if isfield(parameters,'InitialValue')
    set_param(path,'InitialValue',num2str(initialValue,'%.15g'), ...
        'FinalValue',num2str(finalValue,'%.15g'));
else
    set_param(path,'Before',num2str(initialValue,'%.15g'), ...
        'After',num2str(finalValue,'%.15g'));
end
end

function setMATLABFunctionCode(blockPath,code,sampleTime)
% Configure through the official Stateflow.EMChart interface.
try
    blockObject = find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
catch
    bd = bdroot(blockPath);
    blockObject = find(get_param(bd,'Object'), ...
        '-isa','Stateflow.EMChart','Path',blockPath);
end
assert(numel(blockObject) == 1, ...
    'Could not resolve MATLAB Function block: %s',blockPath);
blockObject.Script = code;
if nargin >= 3
    blockObject.ChartUpdate = 'DISCRETE';
    blockObject.SampleTime = num2str(sampleTime,'%.15g');
end
end

function wire(sys,source,destination,signalName)
lineHandle = add_line(sys,source,destination,'autorouting','on');
if nargin >= 4 && ~isempty(signalName)
    try
        set_param(lineHandle,'Name',signalName);
    catch
        % A signal name is explanatory; the completed connection is primary.
    end
end
end

function addAnnotation(sys,position,textValue)
try
    note = Simulink.Annotation(sys,textValue);
    note.Position = position;
    note.FontSize = 11;
catch
    % Annotation support varies slightly; model behaviour is unaffected.
end
end

function clearSystem(sys)
annotations = find_system(sys,'FindAll','on','SearchDepth',1, ...
    'Type','annotation');
for k = 1:numel(annotations)
    try
        delete(get_param(annotations(k),'Object'));
    catch
    end
end

lines = find_system(sys,'FindAll','on','SearchDepth',1,'Type','Line');
for k = 1:numel(lines)
    try
        delete_line(lines(k));
    catch
    end
end

blocks = find_system(sys,'SearchDepth',1,'Type','Block');
blocks = setdiff(blocks,{sys},'stable');
for k = 1:numel(blocks)
    delete_block(blocks{k});
end
end
